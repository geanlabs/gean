package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func TestBoundaries(t *testing.T) {
	tests := []struct {
		name    string
		files   map[string]string
		want    string
		wantErr bool
	}{
		{
			name: "current consensus",
			files: map[string]string{
				"lean/consensus/forkchoice/votes.go": `package forkchoice; import "github.com/geanlabs/gean/lean/consensus/types"`,
				"lean/consensus/types/state.go":      `package types`,
			},
		},
		{
			name: "aliased forbidden import",
			files: map[string]string{
				"lean/consensus/forkchoice/votes.go": `package forkchoice; import db "github.com/geanlabs/gean/lean/internal/store"`,
			},
			want: "lean/consensus/forkchoice -> lean/internal/store",
		},
		{
			name: "tagged generated source is checked",
			files: map[string]string{
				"lean/consensus/types/state_encoding.go": "//go:build future\n\n// Code generated by test. DO NOT EDIT.\npackage types\nimport _ \"github.com/geanlabs/gean/lean/crypto/xmss\"",
			},
			want: "lean/consensus/types -> lean/crypto/xmss",
		},
		{
			name: "external tests obey their boundary",
			files: map[string]string{
				"lean/consensus/types/state_test.go": `package types_test; import "github.com/geanlabs/gean/lean/crypto/xmss"`,
			},
			want: "lean/consensus/types -> lean/crypto/xmss",
		},
		{
			name: "native import in pure consensus",
			files: map[string]string{
				"lean/consensus/forkchoice/votes.go": `package forkchoice; import "C"`,
			},
			want: "lean/consensus/forkchoice -> C",
		},
		{
			name: "malformed imports fail closed",
			files: map[string]string{
				"lean/consensus/types/state.go": "package types\nimport (",
			},
			wantErr: true,
		},
		{
			name: "prefix lookalike is not allowed",
			files: map[string]string{
				"lean/consensus/forkchoice/votes.go": `package forkchoice; import "github.com/geanlabs/gean/lean/consensusextra"`,
			},
			want: "lean/consensus/forkchoice -> lean/consensusextra",
		},
		{
			name: "Lean cannot import Beacon",
			files: map[string]string{
				"lean/internal/chain/import.go": `package chain; import "github.com/geanlabs/gean/beacon/consensus/types"`,
			},
			want: "lean/internal/chain -> beacon/consensus/types",
		},
		{
			name: "protocol boundary follows indirect dependencies",
			files: map[string]string{
				"lean/node/node.go": `package node; import "github.com/geanlabs/gean/helper"`,
				"helper/helper.go":  `package helper; import "github.com/geanlabs/gean/beacon/consensus/types"`,
			},
			want: "lean/node -> helper -> beacon/consensus/types",
		},
		{
			name: "Beacon cannot acquire Lean code through shared packages",
			files: map[string]string{
				"beacon/internal/chain/import.go": `package chain; import "github.com/geanlabs/gean/internal/storage"`,
				"internal/storage/backend.go":     `package storage; import "github.com/geanlabs/gean/lean/internal/store"`,
			},
			want: "beacon/internal/chain -> internal/storage -> lean/internal/store",
		},
		{
			name: "module root cannot hide protocol dependencies",
			files: map[string]string{
				"lean/node/node.go": `package node; import "github.com/geanlabs/gean"`,
				"gean.go":           `package gean; import "github.com/geanlabs/gean/beacon/consensus/types"`,
			},
			want: "lean/node -> . -> beacon/consensus/types",
		},
		{
			name: "shared mechanics cannot acquire protocol types",
			files: map[string]string{
				"internal/lifecycle/group.go": `package lifecycle; import "github.com/geanlabs/gean/lean/consensus/types"`,
			},
			want: "internal/lifecycle -> lean/consensus/types",
		},
		{
			name: "Beacon may use shared mechanics",
			files: map[string]string{
				"beacon/internal/chain/import.go": `package chain; import "github.com/geanlabs/gean/internal/storage"`,
				"internal/storage/backend.go":     `package storage`,
			},
		},
		{
			name: "Beacon consensus may use Beacon crypto",
			files: map[string]string{
				"beacon/consensus/statetransition/block.go": `package statetransition; import "github.com/geanlabs/gean/beacon/crypto/bls"`,
				"beacon/crypto/bls/verify.go":               `package bls; import "C"`,
			},
		},
		{
			name: "Beacon consensus cannot reach node services",
			files: map[string]string{
				"beacon/consensus/forkchoice/store.go": `package forkchoice; import "github.com/geanlabs/gean/beacon/internal/store"`,
			},
			want: "beacon/consensus/forkchoice -> beacon/internal/store",
		},
		{
			name: "crypto cannot depend on protocol containers",
			files: map[string]string{
				"beacon/crypto/bls/verify.go": `package bls; import "github.com/geanlabs/gean/beacon/consensus/types"`,
			},
			want: "beacon/crypto/bls -> beacon/consensus/types",
		},
		{
			name: "validator client reaches the node only through its API",
			files: map[string]string{
				"beacon/validator/internal/duties/duties.go": `package duties; import "github.com/geanlabs/gean/beacon/internal/chain"`,
			},
			want: "beacon/validator/internal/duties -> beacon/internal/chain",
		},
		{
			name: "dependency tests do not contaminate production graph",
			files: map[string]string{
				"lean/node/node.go":     `package node; import "github.com/geanlabs/gean/helper"`,
				"helper/helper.go":      `package helper`,
				"helper/helper_test.go": `package helper_test; import "github.com/geanlabs/gean/beacon/consensus/types"`,
			},
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			root := t.TempDir()
			tt.files["go.mod"] = "module " + module + "\n"
			for name, contents := range tt.files {
				path := filepath.Join(root, name)
				if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
					t.Fatal(err)
				}
				if err := os.WriteFile(path, []byte(contents), 0o600); err != nil {
					t.Fatal(err)
				}
			}
			problems, err := check(root)
			if tt.wantErr {
				if err == nil {
					t.Fatal("expected a parse error")
				}
				return
			}
			if err != nil {
				t.Fatal(err)
			}
			if tt.want == "" {
				if len(problems) != 0 {
					t.Fatalf("unexpected violations: %v", problems)
				}
			} else if !strings.Contains(strings.Join(problems, "\n"), tt.want) {
				t.Fatalf("violations %v do not include %q", problems, tt.want)
			}
		})
	}
}
